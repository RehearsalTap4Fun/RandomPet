import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
import {chromium} from '@playwright/test'
import sharp from 'sharp'
const browser=await chromium.launch({headless:true})
const key='qmonster.feline-combination-candidate.v1'
const report={checks:[],pageErrors:[]}
try{
 const page=await browser.newPage({acceptDownloads:true})
 page.on('pageerror',error=>report.pageErrors.push(error.message))
 await page.goto('http://127.0.0.1:4184/')
 const ready=()=>page.waitForFunction(()=>document.querySelector('.feline-primary')&&!document.querySelector('.feline-primary').disabled)
 const state=()=>page.evaluate(key=>JSON.parse(localStorage.getItem(key)),key)
 await ready()
 await page.getByRole('button',{name:'小龙角',exact:true}).click()
 await page.getByRole('button',{name:'鹿角',exact:true}).click()
 assert.equal((await state()).selections.crown,'antlers')
 assert.equal(await page.getByRole('button',{name:'小龙角',exact:true}).getAttribute('aria-pressed'),'false')
 report.checks.push('手动替换同位置角，未同时保留两种角')
 await page.getByLabel('锁定花纹',{exact:true}).check()
 const locked=await state()
 await page.getByRole('button',{name:'重掷未锁定位置 ↻',exact:true}).click()
 const rerolled=await state()
 assert.equal(rerolled.selections.coat,locked.selections.coat)
 assert.equal(rerolled.rolls.coat,locked.rolls.coat)
 assert.equal(rerolled.rolls.crown,locked.rolls.crown+1)
 report.checks.push('整体重掷保留锁定花纹及其计数')
 await ready()
 await page.getByText('保存与恢复规格',{exact:true}).click()
 const downloadSpec=page.waitForEvent('download')
 await page.getByRole('button',{name:'导出规格 JSON',exact:true}).click()
 const downloaded=JSON.parse(await fs.readFile(await (await downloadSpec).path(),'utf8'))
 assert.deepEqual(downloaded,await state())
 await page.reload();await ready()
 assert.deepEqual(await state(),downloaded)
 report.checks.push('JSON 导出及刷新恢复完整状态')
 const downloadPng=page.waitForEvent('download')
 await page.getByRole('button',{name:'导出透明 PNG',exact:true}).click()
 const png=await fs.readFile(await (await downloadPng).path())
 const metadata=await sharp(png).metadata()
 assert.equal(metadata.width,1254);assert.equal(metadata.height,1254);assert.equal(metadata.hasAlpha,true)
 const alpha=await sharp(png).extractChannel('alpha').raw().toBuffer()
 assert(alpha.includes(0));assert(alpha.some(value=>value>0))
 report.checks.push('实际 PNG 导出尺寸与透明像素有效')
 await page.getByText('保存与恢复规格',{exact:true}).click()
 await page.locator('#feline-import-json').fill('{broken-json')
 await page.getByRole('button',{name:'应用规格',exact:true}).click()
 assert.match(await page.getByRole('alert').innerText(),/JSON 格式错误/)
 assert.deepEqual(await state(),downloaded)
 report.checks.push('非法 JSON 明确报错并保留当前有效规格')
 await page.route('**/orange-white-small-fangs.png',route=>route.fulfill({status:404,body:'missing'}))
 const invalidResourceSpec=structuredClone(downloaded)
 invalidResourceSpec.selections={coat:'orange-white',expression:'small-fangs',crown:'none',ears:'none',neck:'none',back:'none',tailTip:'none'}
 await page.locator('#feline-import-json').fill(JSON.stringify(invalidResourceSpec))
 await page.getByRole('button',{name:'应用规格',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('[role=alert]')?.textContent.includes('404'))
 assert.equal(await page.getByRole('button',{name:'导出透明 PNG',exact:true}).isEnabled(),false)
 assert.equal(await page.locator('canvas').evaluate(canvas=>canvas.getContext('2d').getImageData(0,0,1254,1254).data.some((v,i)=>i%4===3&&v!==0)),false)
 report.checks.push('资源 404 时画布清空且 PNG 导出禁用')
 assert.deepEqual(report.pageErrors,[])
 report.passed=true
}catch(error){report.passed=false;report.error=String(error);throw error}finally{
 await fs.writeFile(new URL('../docs/qa/workbench-verification.json',import.meta.url),JSON.stringify(report,null,2)+'\n')
 await browser.close()
 console.log(JSON.stringify(report))
}
